function build_filter_mex(root)
% Build for MATLAB R2017a after make filter-native.
if nargin==0,root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));end
out=fullfile(root,'build','filter','matlab-mex');if ~exist(out,'dir'),mkdir(out);end
mex('-largeArrayDims','CFLAGS=$CFLAGS -O3 -std=c99',...
 ['-I' fullfile(root,'runtime','filter','include')],...
 ['-L' fullfile(root,'build','filter','release')],...
 fullfile(root,'runtime','filter','matlab','sdl_filter_mex.c'),...
 '-lsdl_filter','LDFLAGS=$LDFLAGS -Wl,-rpath,\$ORIGIN/../release','-outdir',out);
end
