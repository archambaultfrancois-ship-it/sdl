#!/usr/bin/env python3
"""Ada 2012 typed bindings; direct Ada Packed codecs with C dynamic schema-evolution fallback."""
import os
import re
import copy
from generator import (canonical_type_descriptor, clear_generated_outputs, parse_schemas,
   TypeTable, validate_package_paths, validate_file_dependencies)

_ADA_KEYWORDS = set(('abort abs abstract accept access aliased all and array at begin body case '
   'constant declare delay delta digits do else elsif end entry exception exit for function '
   'generic goto if in interface is limited loop mod new not null of or others out overriding '
   'package pragma private procedure protected raise range record rem renames requeue return '
   'reverse select separate some subtype synchronized tagged task terminate then type until use '
   'when while with xor').split())


def stem(name):
   result = re.sub('[^A-Za-z0-9_]', '_Anon_', name)
   return re.sub('_+', '_', result).strip('_') or 'Anon'


def typ(name):
   return 'T_' + stem(name)


def ada_package(package, base):
   return '.'.join(['SDL'] + [stem(part) for part in package.split('.')] + [stem(base)]) if package else 'SDL_' + stem(base)


PRIMITIVES = {'bool': 'Boolean', 'int8': 'Int8', 'uint8': 'Unsigned_8', 'int16': 'Int16', 'uint16': 'Unsigned_16',
   'int32': 'Int32', 'uint32': 'Unsigned_32', 'int64': 'Int64', 'uint64': 'Unsigned_64', 'fl32': 'Float32', 'fl64': 'Float64',
   'c32': 'Complex32', 'c64': 'Complex64', 'string': 'Text'}


def quote(text):
   return '"' + text.replace('"', '""') + '"'


class AdaBackend:
   def __init__(self, schema, package):
      self.own_types = set(schema.messages) | set(schema.enums)
      self.schema = copy.copy(schema)
      messages, enums = schema.catalogue_types()
      self.schema.messages = TypeTable(messages)
      self.schema.enums = TypeTable(enums)
      self.schema.message_order = list(messages)
      self.schema._order_embedded_messages()
      self.package = package

   def external_package(self, name):
      if name in self.own_types:
         return None
      package, base = self.schema.type_owners[name]
      return ada_package(package, base)

   def validate(self):
      seen = set()
      def reserve(identifier):
         key = identifier.lower()
         if key in seen:
            raise ValueError('Ada generated declaration collision: ' + identifier)
         seen.add(key)
      for name in list(self.schema.messages) + list(self.schema.enums):
         key = typ(name).lower()
         if key in seen:
            raise ValueError('Ada type name collision: ' + name)
         seen.add(key)
      for enum in self.schema.enums.values():
         for item, _ in enum.pairs:
            reserve('E_' + stem(enum.name) + '_' + stem(item))
      for message in self.schema.messages.values():
         fields = set()
         for f in message.fields:
            key = stem(f.name).lower()
            if key in fields:
               raise ValueError('Ada field name collision: ' + message.name + '.' + f.name)
            fields.add(key)
            for depth in range(len(f.array_dimensions)):
               reserve(self.array_name(message.name, f, depth))
            if f.modifier in ('packed', 'repeated'):
               reserve('V_' + stem(message.name) + '_' + stem(f.name))
            if any(n > 2147483647 for n in f.array_dimensions):
               raise ValueError('Ada fixed array dimension exceeds Positive range')
      for enum in self.schema.enums.values():
         names = [stem(n).lower() for n, _ in enum.pairs]
         if len(names) != len(set(names)):
            raise ValueError('Ada enum constant collision: ' + enum.name)

   def base(self, name):
      return PRIMITIVES.get(name, typ(name))

   def default(self, name):
      if name in self.schema.enums:
         return 'E_' + stem(name) + '_' + stem(self.schema.enums[name].pairs[0][0])
      return {'bool': 'False', 'string': 'Null_Unbounded_String',
         'c32': '(others => 0.0)', 'c64': '(others => 0.0)',
         'fl32': '0.0', 'fl64': '0.0'}.get(name, '(others => <>)' if name in self.schema.messages else '0')

   def array_name(self, msg, field, depth=0):
      return 'A_' + stem(msg) + '_' + stem(field.name) + '_' + str(depth)

   def field_type(self, msg, f):
      return self.array_name(msg, f) if f.array_dimensions else self.base(f.type_name)

   def spec(self):
      out = ['-- Generated by the SDL Ada backend.\nwith SDL_Runtime; use SDL_Runtime;\n',
         'with Ada.Containers.Vectors;\nwith Ada.Strings.Unbounded; use Ada.Strings.Unbounded;\n',
         'with Interfaces; use Interfaces;\n']
      for package, base in self.schema.dependencies():
         out.append('with ' + ada_package(package, base) + ';\n')
      out.append('package ' + self.package + ' is\n')
      desc = canonical_type_descriptor(self.schema).decode('utf-8')
      out.append('   Description : constant String :=\n      ' + ' &\n      '.join(quote(desc[i:i+200]) for i in range(0, len(desc), 200)) + ';\n')
      out.append('   function Prepare (Catalogue : String := Description; Use_Direct : Boolean := True) return Context;\n')
      for enum in self.schema.enums.values():
         owner = self.external_package(enum.name)
         out.append('   subtype ' + typ(enum.name) + ' is ' + (owner + '.' + typ(enum.name) if owner else 'Int32') + ';\n')
         for item, n in enum.pairs:
            out.append('   E_' + stem(enum.name) + '_' + stem(item) + ' : constant ' + typ(enum.name) + ' := ' + str(n) + ';\n')
         out.append('   function Valid_' + stem(enum.name) + ' (V : ' + typ(enum.name) + ') return Boolean;\n')
      for name in self.schema.message_order:
         message = self.schema.messages[name]
         owner = self.external_package(name)
         for f in message.fields:
            for d in reversed(range(len(f.array_dimensions))):
               if owner:
                  out.append('   subtype ' + self.array_name(name, f, d) + ' is ' + owner + '.' + self.array_name(name, f, d) + ';\n')
                  continue
               child = self.array_name(name, f, d+1) if d+1 < len(f.array_dimensions) else self.base(f.type_name)
               out.append('   type ' + self.array_name(name, f, d) + ' is array (Positive range 1 .. ' + str(f.array_dimensions[d]) + ') of ' + child + ';\n')
            if f.modifier in ('packed', 'repeated'):
               declaration = ('renames ' + owner + '.V_' + stem(name) + '_' + stem(f.name)) if owner else ('is new Ada.Containers.Vectors (Positive, ' + self.field_type(name, f) + ')')
               out.append('   package V_' + stem(name) + '_' + stem(f.name) + ' ' + declaration + ';\n')
         if owner:
            out.append('   subtype ' + typ(name) + ' is ' + owner + '.' + typ(name) + ';\n')
            out.append('   use type ' + typ(name) + ';\n')
         else:
            out.append('   type ' + typ(name) + ' is ' + ('null record;\n' if not message.fields else 'record\n'))
         for f in ([] if owner else message.fields):
            if f.modifier == 'optional':
               out.append('      H_' + stem(f.name) + ' : Boolean := False;\n')
            t = self.field_type(name, f)
            default = self.default(f.type_name)
            for _ in f.array_dimensions:
               default = '(others => ' + default + ')'
            if f.modifier in ('packed', 'repeated'):
               t = 'V_' + stem(name) + '_' + stem(f.name) + '.Vector'
               default = None
            out.append('      F_' + stem(f.name) + ' : ' + t + ((' := ' + default) if default else '') + ';\n')
         if message.fields and not owner:
            out.append('   end record;\n')
         out.append('   function Encode (C : Context; M : ' + typ(name) + ') return Bytes;\n')
         out.append('   function Decode (C : Context; Data : Bytes) return ' + typ(name) + ';\n')
      out.append('end ' + self.package + ';\n')
      return ''.join(out)

   def write(self, name, dims, value, indent='      ', depth=0):
      if dims:
         i = 'I_' + str(depth)
         return indent + 'for ' + i + ' in ' + value + "'Range loop\n" + self.write(name, dims[1:], value+'('+i+')', indent+'   ', depth+1) + indent+'end loop;\n'
      if name in self.schema.messages:
         return indent + 'Write_' + typ(name) + ' (C, B, ' + value + ');\n'
      prefix = ''
      if name in self.schema.enums:
         prefix = indent + 'if not Valid_' + stem(name) + ' (' + value + ') then raise Codec_Error with "invalid enum"; end if;\n'
      return prefix + indent + 'Write (B, ' + value + ');\n'

   def read(self, name, dims, target, value, indent='         ', depth=0):
      if dims:
         i, v = 'I_' + str(depth), 'X_' + str(depth)
         return (indent + 'if Length (' + value + ') /= ' + str(dims[0]) + ' then raise Codec_Error with "fixed array length"; end if;\n' +
            indent + 'for ' + i + ' in ' + target + "'Range loop\n" +
            indent + '   declare ' + v + ' : constant Value := Item (' + value + ', ' + i + ' - ' + target + "'First); begin\n" +
            self.read(name, dims[1:], target+'('+i+')', v, indent+'      ', depth+1) + indent+'   end;\n'+indent+'end loop;\n')
      expr = 'Read_' + typ(name) + ' (C, Message (' + value + '))' if name in self.schema.messages else 'Read (' + value + ')'
      out = indent + target + ' := ' + expr + ';\n'
      if name in self.schema.enums:
         out += indent + 'if not Valid_' + stem(name) + ' (' + target + ') then raise Codec_Error with "invalid local enum"; end if;\n'
      return out

   def body(self):
      from ada_direct import DirectCodecs
      direct = DirectCodecs(self)
      out = ['-- Generated by the SDL Ada backend.\nwith System;\nwith Interfaces; use Interfaces;\n', 'package body ' + self.package + ' is\n',
         '   function Prepare (Catalogue : String := Description; Use_Direct : Boolean := True) return Context is\n   begin return SDL_Runtime.Prepare (Catalogue, Description, Use_Direct); end;\n']
      for enum in self.schema.enums.values():
         values = ' | '.join(str(v) for _, v in enum.pairs)
         out.append('   function Valid_' + stem(enum.name) + ' (V : ' + typ(enum.name) + ') return Boolean is\n   begin return V in ' + values + '; end;\n')
      out.append(direct.helpers())
      for name in self.schema.message_order:
         out.append('   procedure Write_' + typ(name) + ' (C : Context; B : in out Buffer; M : ' + typ(name) + ');\n')
         out.append('   function Read_' + typ(name) + ' (C : Context; Tree : Value) return ' + typ(name) + ';\n')
      for name in self.schema.message_order:
         msg = self.schema.messages[name]
         out.append('   procedure Write_' + typ(name) + ' (C : Context; B : in out Buffer; M : ' + typ(name) + ') is\n   begin\n      Check_Encode (C, '+quote(name)+');\n')
         for f in sorted(msg.fields, key=lambda x:x.index):
            value = 'M.F_' + stem(f.name)
            if f.modifier == 'optional':
               out.append('      Put_Count (B, (if M.H_'+stem(f.name)+' then 1 else 0));\n      if M.H_'+stem(f.name)+' then\n')
               out.append(self.write(f.type_name, f.array_dimensions, value, '         '))
               out.append('      end if;\n')
            elif f.modifier in ('packed','repeated'):
               out.append('      Put_Count (B, Unsigned_32 ('+value+'.Length));\n      for Element of '+value+' loop\n')
               out.append(self.write(f.type_name, f.array_dimensions, 'Element', '         '))
               out.append('      end loop;\n')
            else:
               out.append(self.write(f.type_name, f.array_dimensions, value))
         out.append('   end;\n')
         out.append('   function Read_'+typ(name)+' (C : Context; Tree : Value) return '+typ(name)+' is\n      Result : '+typ(name)+';\n'+('      V : Value;\n' if msg.fields else '')+'   begin\n      if Name_Of (Tree) /= '+quote(name)+' then raise Codec_Error with "wrong message type"; end if;\n')
         for f in sorted(msg.fields, key=lambda x:x.index):
            out.append('      V := Field (C, Tree, '+str(f.index)+');\n      if Present (V) then\n')
            if f.modifier == 'optional':
               out.append('         Result.H_'+stem(f.name)+' := True;\n')
            if f.modifier in ('packed','repeated'):
               out.append('         for I in 1 .. Length (V) loop\n            declare\n               X : constant Value := Item (V, I - 1);\n               Element : '+self.field_type(name,f)+';\n            begin\n')
               out.append(self.read(f.type_name, f.array_dimensions, 'Element', 'X', '               '))
               out.append('               Result.F_'+stem(f.name)+'.Append (Element);\n            end;\n         end loop;\n')
            else:
               out.append(self.read(f.type_name,f.array_dimensions,'Result.F_'+stem(f.name),'V'))
            out.append('      end if;\n')
         out.append('      return Result;\n   end;\n')
         out.append('   function Encode (C : Context; M : '+typ(name)+') return Bytes is\n      B : Buffer;\n   begin\n'+direct.encode(name)+'      Put_Count (B, Message_Id (C, '+quote(name)+'));\n      Write_'+typ(name)+' (C, B, M);\n      declare Data : constant Bytes := Represent (C, To_Bytes (B)); begin Check_Wire (C, Data); return Data; end;\n   exception when Constraint_Error => raise Codec_Error with "encoding range error";\n   end;\n')
         out.append('   function Decode (C : Context; Data : Bytes) return '+typ(name)+' is\n      Tree : Value := System.Null_Address;\n   begin\n'+direct.decode(name)+'      Tree := Decode_Tree (C, Data);\n      declare Result : constant '+typ(name)+' := Read_'+typ(name)+' (C, Tree); begin Free_Tree (Tree); Tree := System.Null_Address; return Result; end;\n   exception when Constraint_Error => Free_Tree (Tree); raise Codec_Error with "decoding range error"; when others => Free_Tree (Tree); raise;\n   end;\n')
      out.append('end '+self.package+';\n')
      return ''.join(out)


def generate_ada(input_path, output_dir):
   schemas = parse_schemas(input_path)
   validate_file_dependencies(schemas, 'Ada')
   validate_package_paths(schemas, 'Ada', lambda name: name.lower() not in _ADA_KEYWORDS)
   backends = []
   seen = set()
   for base, _, schema in schemas:
      package = ada_package(schema.package, base)
      if schema.package and (stem(base).lower() in _ADA_KEYWORDS or
            not re.fullmatch(r'[A-Za-z][A-Za-z0-9]*(?:_[A-Za-z0-9]+)*', stem(base))):
         raise ValueError('invalid Ada schema package name: ' + base)
      if package.lower() in seen or package.lower() == 'sdl_runtime':
         raise ValueError('Ada package name collision: ' + base)
      seen.add(package.lower())
      backend = AdaBackend(schema, package)
      backend.validate()
      backends.append(backend)
   parents = set()
   normalized_parents = {}
   for backend in backends:
      parts = backend.package.split('.')
      parents.update('.'.join(parts[:i]) for i in range(1, len(parts)))
      original = ['SDL'] + backend.schema.package.split('.') if backend.schema.package else []
      for i in range(1, len(original) + 1):
         raw = '.'.join(original[:i])
         converted = '.'.join(stem(p) for p in original[:i]).lower()
         if converted in normalized_parents and normalized_parents[converted] != raw:
            raise ValueError('Ada package name collision: ' + raw)
         normalized_parents[converted] = raw
   for parent in sorted(parents):
      if parent.lower() in seen:
         raise ValueError('Ada parent package conflicts with schema package: ' + parent)
   os.makedirs(output_dir, exist_ok=True)
   clear_generated_outputs(output_dir, ('.ads','.adb'), ('-- Generated by the SDL Ada backend.',))
   for parent in sorted(parents):
      with open(os.path.join(output_dir, parent.lower().replace('.', '-') + '.ads'), 'w', encoding='utf-8') as output:
         output.write('-- Generated by the SDL Ada backend.\npackage ' + parent + ' is\nend ' + parent + ';\n')
   for backend in backends:
      for suffix, source in (('.ads',backend.spec()),('.adb',backend.body())):
         with open(os.path.join(output_dir,backend.package.lower().replace('.', '-')+suffix),'w',encoding='utf-8') as output:
            output.write(source)
