#!/usr/bin/env python3
"""Rust code generator for the shared SDL schema model."""

import os

from generator import (c_identifier, canonical_type_descriptor,
   canonical_type_hash, parse_schemas)


def rust_variant(name):
   parts = [part for part in name.replace('-', '_').split('_') if part]
   return ''.join(part[:1].upper() + part[1:].lower() for part in parts)


def rust_type_name(name):
   if '$' in name:
      parent, sequence = name.split('$', 1)
      return c_identifier(parent) + sequence
   return c_identifier(name)


class RustBackend:
   def __init__(self, schema):
      self.schema = schema

   def _rust_type(self, name):
      mapping = {
         'bool': 'bool',
         'int8': 'i8',
         'int16': 'i16',
         'int32': 'i32',
         'int64': 'i64',
         'fl32': 'f32',
         'fl64': 'f64',
         'c32': 'Complex32',
         'c64': 'Complex64',
         'string': 'String',
      }
      return mapping.get(name, rust_type_name(name))

   def _rust_field_type(self, field):
      value_type = self._rust_type(field.type_name)
      for dimension in reversed(field.array_dimensions):
         value_type = '[' + value_type + '; ' + str(dimension) + ']'
      return value_type

   def generate(self):
      used_types = {field.type_name for message in self.schema.messages.values()
         for field in message.fields}
      imports = ['CodecError', 'SdlMessage', 'WireValue', 'write_field']
      has_packed_fields = any(field.modifier == 'packed'
         for message in self.schema.messages.values() for field in message.fields)
      has_fixed_messages = any(self.schema.fixed_wire_size(name) is not None
         for name in self.schema.message_order)
      if has_packed_fields:
         imports.extend(['read_packed_field', 'write_packed_field'])
      if has_fixed_messages or self.schema.enums:
         imports.append('FixedWire')
      if 'c32' in used_types:
         imports.append('Complex32')
      if 'c64' in used_types:
         imports.append('Complex64')
      output = [
         '// Generated by the SDL Rust backend.\n',
         'use sdl_runtime::{' + ', '.join(imports) + '};\n\n',
      ]

      for enum in self.schema.enums.values():
         variants = [(rust_variant(name), value) for name, value in enum.pairs]
         if not variants:
            raise ValueError('Rust enums must declare at least one value: ' + enum.name)
         for variant, value in variants:
            if int(value) < -2147483648 or int(value) > 2147483647:
               raise ValueError('enum values must fit in i32 for Rust: ' + enum.name)
         output.append('#[derive(Clone, Copy, Debug, PartialEq)]\n')
         output.append('#[repr(i32)]\n')
         output.append('pub enum ' + c_identifier(enum.name) + ' {\n')
         for variant, value in variants:
            output.append('   ' + variant + ' = ' + value + ',\n')
         output.append('}\n')
         output.append('impl Default for ' + c_identifier(enum.name) + ' {\n')
         output.append('   fn default() -> Self { Self::' + variants[0][0] + ' }\n')
         output.append('}\n')
         output.append('impl WireValue for ' + c_identifier(enum.name) + ' {\n')
         output.append('   fn encode_payload(&self) -> Result<Vec<u8>, CodecError> {\n')
         output.append('      (*self as i32).encode_payload()\n   }\n')
         output.append('   fn decode_payload(payload: &[u8]) -> Result<Self, CodecError> {\n')
         output.append('      match i32::decode_payload(payload)? {\n')
         for variant, value in variants:
            output.append('         ' + value + ' => Ok(Self::' + variant + '),\n')
         output.append('         _ => Err(CodecError::InvalidEnum),\n')
         output.append('      }\n   }\n}\n\n')
         output.append('impl FixedWire for ' + c_identifier(enum.name) + ' {\n')
         output.append('   const WIRE_SIZE: usize = 4;\n')
         output.append('   fn encode_fixed(&self, output: &mut Vec<u8>) -> Result<(), CodecError> {\n')
         output.append('      (*self as i32).encode_fixed(output)\n   }\n')
         output.append('   fn decode_fixed(payload: &[u8]) -> Result<Self, CodecError> {\n')
         output.append('      <Self as WireValue>::decode_payload(payload)\n   }\n}\n\n')

      for message_name in self.schema.message_order:
         message = self.schema.messages[message_name]
         fields = sorted(message.fields, key=lambda field: field.index)
         rust_name = rust_type_name(message_name)
         output.append('#[derive(Clone, Debug, Default, PartialEq)]\n')
         output.append('pub struct ' + rust_name + ' {\n')
         for field in fields:
            rust_field = c_identifier(field.name)
            value_type = self._rust_field_type(field)
            if field.modifier == 'optional':
               value_type = 'Option<' + value_type + '>'
            elif field.modifier in ('repeated', 'packed'):
               value_type = 'Vec<' + value_type + '>'
            output.append('   pub ' + rust_field + ': ' + value_type + ',\n')
         output.append('}\n')

         output.append('impl WireValue for ' + rust_name + ' {\n')
         output.append('   fn encode_payload(&self) -> Result<Vec<u8>, CodecError> {\n')
         output.append('      <Self as SdlMessage>::encode_body(self)\n   }\n')
         output.append('   fn decode_payload(payload: &[u8]) -> Result<Self, CodecError> {\n')
         output.append('      <Self as SdlMessage>::decode_body(payload)\n   }\n}\n')

         output.append('impl SdlMessage for ' + rust_name + ' {\n')
         output.append('   const HASH: u32 = 0x' + format(
            canonical_type_hash(self.schema, message_name), '08X') + ';\n')
         descriptor = canonical_type_descriptor(self.schema, message_name)
         descriptor_lines = []
         for offset in range(0, len(descriptor), 16):
            descriptor_lines.append(', '.join('0x%02X' % byte for byte in
               descriptor[offset:offset + 16]))
         output.append('   const DESCRIPTOR: &\'static [u8] = &[' +
            '\n      ' + ',\n      '.join(descriptor_lines) + '\n   ];\n')
         output.append('   fn encode_fields(&self, output: &mut Vec<u8>) -> Result<(), CodecError> {\n')
         for field in fields:
            rust_field = c_identifier(field.name)
            if field.modifier == 'optional':
               output.append('      if let Some(value) = &self.' + rust_field + ' {\n')
               output.append('         write_field(' + str(field.index) + ', value, output)?;\n')
               output.append('      }\n')
            elif field.modifier == 'packed':
               output.append('      write_packed_field(' + str(field.index) +
                  ', &self.' + rust_field + ', output)?;\n')
            elif field.modifier == 'repeated':
               output.append('      for value in &self.' + rust_field + ' {\n')
               output.append('         write_field(' + str(field.index) + ', value, output)?;\n')
               output.append('      }\n')
            else:
               output.append('      write_field(' + str(field.index) + ', &self.' +
                  rust_field + ', output)?;\n')
         output.append('      Ok(())\n   }\n')

         output.append('   fn decode_field(&mut self, id: u32, payload: &[u8]) -> Result<(), CodecError> {\n')
         output.append('      match id {\n')
         for field in fields:
            rust_field = c_identifier(field.name)
            value_type = self._rust_field_type(field)
            if field.modifier == 'optional':
               decoded = 'Some(<' + value_type + ' as WireValue>::decode_payload(payload)?)'
            elif field.modifier == 'packed':
               decoded = 'read_packed_field::<' + value_type + '>(payload)?'
            elif field.modifier == 'repeated':
               decoded = '<' + value_type + ' as WireValue>::decode_payload(payload)?'
            else:
               decoded = '<' + value_type + ' as WireValue>::decode_payload(payload)?'
            output.append('         ' + str(field.index) + ' => {\n')
            if field.modifier in ('repeated', 'packed'):
               if field.modifier == 'packed':
                  output.append('            self.' + rust_field + '.extend(' + decoded + ');\n')
                  output.append('            Ok(())\n         }\n')
                  continue
               output.append('            self.' + rust_field + '.push(' + decoded + ');\n')
            else:
               output.append('            self.' + rust_field + ' = ' + decoded + ';\n')
            output.append('            Ok(())\n         }\n')
         output.append('         _ => Ok(()),\n')
         output.append('      }\n   }\n}\n\n')
         fixed_size = self.schema.fixed_wire_size(message_name)
         if fixed_size is not None:
            output.append('impl FixedWire for ' + rust_name + ' {\n')
            output.append('   const WIRE_SIZE: usize = ' + str(fixed_size) + ';\n')
            output.append('   fn encode_fixed(&self, output: &mut Vec<u8>) -> Result<(), CodecError> {\n')
            for field in fields:
               output.append('      self.' + c_identifier(field.name) + '.encode_fixed(output)?;\n')
            output.append('      Ok(())\n   }\n')
            output.append('   fn decode_fixed(payload: &[u8]) -> Result<Self, CodecError> {\n')
            output.append('      if payload.len() != Self::WIRE_SIZE { return Err(CodecError::TypeMismatch); }\n')
            for index, field in enumerate(fields):
               rust_field = c_identifier(field.name)
               value_type = self._rust_field_type(field)
               output.append('      let ' + rust_field + ' = <' + value_type +
                  ' as FixedWire>::decode_fixed(&payload[' +
                  ('0' if index == 0 else 'offset') + '..' +
                  ('<'+value_type+' as FixedWire>::WIRE_SIZE' if index == 0 else
                   'offset + <' + value_type + ' as FixedWire>::WIRE_SIZE') +
                  '])?;\n')
               if index + 1 < len(fields):
                  output.append('      let offset = ' +
                     ('<'+value_type+' as FixedWire>::WIRE_SIZE' if index == 0 else
                      'offset + <' + value_type + ' as FixedWire>::WIRE_SIZE') + ';\n')
            output.append('      Ok(Self {\n')
            for field in fields:
               rust_field = c_identifier(field.name)
               output.append('         ' + rust_field + ': ' + rust_field + ',\n')
            output.append('      })\n   }\n}\n\n')
      return ''.join(output)

def generate_rust(input_path, output_dir):
   schemas = parse_schemas(input_path)
   os.makedirs(output_dir, exist_ok=True)
   modules = []
   seen_modules = set()
   for base_name, unused_identifier, parser in schemas:
      module_name = c_identifier(base_name).lower()
      if module_name in seen_modules:
         raise ValueError('SDL filenames map to the same Rust module: ' + module_name)
      seen_modules.add(module_name)
      with open(os.path.join(output_dir, module_name + '.rs'), 'w', encoding='utf-8') as output_file:
         output_file.write(RustBackend(parser).generate())
      modules.append(module_name)

   with open(os.path.join(output_dir, 'mod.rs'), 'w', encoding='utf-8') as output_file:
      output_file.write('// Generated SDL modules.\n')
      for module in modules:
         output_file.write('pub mod ' + module + ';\n')
