#!/usr/bin/env python3
"""SDL parser and C descriptor backend."""

import os
import re
import sys


def fnv1a_32(string_data):
   value = 2166136261
   for char in string_data:
      value = ((value ^ ord(char)) * 16777619) & 0xFFFFFFFF
   return value


def c_identifier(value):
   identifier = re.sub(r'\W', '_', value)
   if not identifier or identifier[0].isdigit():
      identifier = '_' + identifier
   return identifier


class Field:
   def __init__(self, index, modifier, type_name, name):
      self.index = int(index)
      self.modifier = modifier
      self.type_name = type_name
      self.name = name


class Message:
   def __init__(self, name):
      self.name = name
      self.fields = []


class Enum:
   def __init__(self, name):
      self.name = name
      self.pairs = []


class MsgParser:
   BUILTINS = {'bool', 'int8', 'int16', 'int32', 'int64', 'fl32', 'fl64',
      'c32', 'c64', 'string'}

   def __init__(self):
      self.enums = {}
      self.messages = {}
      self.message_order = []

   def parse_text(self, text):
      current_enum = None
      current_msg = None
      for raw_line in text.splitlines():
         line = re.sub(r'//.*', '', raw_line).strip()
         if not line:
            continue
         match = re.match(r'enum\s+(\w+)\s*\{?$', line)
         if match:
            name = match.group(1)
            if name in self.enums or name in self.messages:
               raise ValueError('duplicate type name: ' + name)
            current_enum = Enum(name)
            self.enums[name] = current_enum
            current_msg = None
            continue
         match = re.match(r'message\s+(\w+)\s*\{?$', line)
         if match:
            name = match.group(1)
            if name in self.enums or name in self.messages:
               raise ValueError('duplicate type name: ' + name)
            current_msg = Message(name)
            self.messages[name] = current_msg
            self.message_order.append(name)
            current_enum = None
            continue
         if line == '}':
            current_enum = None
            current_msg = None
            continue
         if current_enum is not None:
            match = re.match(r'(\w+)\s*=\s*(-?\d+)\s*;', line)
            if not match:
               raise ValueError('invalid enum entry: ' + line)
            current_enum.pairs.append((match.group(1), match.group(2)))
            continue
         if current_msg is not None:
            match = re.match(r'(\d+):\s+(optional|required|repeated)\s+(\w+)\s+(\w+)\s*;', line)
            if not match:
               raise ValueError('invalid field declaration: ' + line)
            current_msg.fields.append(Field(match.group(1), match.group(2),
               match.group(3), match.group(4)))
            continue
         raise ValueError('unexpected SDL statement: ' + line)
      self.validate()

   def validate(self):
      for message in self.messages.values():
         ids = set()
         names = set()
         for field in message.fields:
            if field.index <= 0 or field.index > 0xFFFFFFFF:
               raise ValueError('field ID must fit in a nonzero uint32')
            if field.index in ids or field.name in names:
               raise ValueError('duplicate field ID or name in ' + message.name)
            if field.type_name not in self.BUILTINS and field.type_name not in self.enums and field.type_name not in self.messages:
               raise ValueError('unknown type ' + field.type_name + ' in ' + message.name)
            ids.add(field.index)
            names.add(field.name)
      for enum in self.enums.values():
         names = set()
         values = set()
         for name, value in enum.pairs:
            if name in names or int(value) in values:
               raise ValueError('duplicate enum name or value in ' + enum.name)
            names.add(name)
            values.add(int(value))

   def _c_type(self, name):
      return {'bool': 'bool', 'int8': 'int8_t', 'int16': 'int16_t', 'int32': 'int32_t',
         'int64': 'int64_t', 'fl32': 'float', 'fl64': 'double',
         'c32': 'float complex', 'c64': 'double complex',
         'string': 'const char *'}.get(name, name)

   def _type_desc(self, name):
      descriptors = {'bool': 'SDL_BOOL_DESC', 'int8': 'SDL_INT8_DESC', 'int16': 'SDL_INT16_DESC',
         'int32': 'SDL_INT32_DESC', 'int64': 'SDL_INT64_DESC',
         'fl32': 'SDL_FLOAT32_DESC', 'fl64': 'SDL_FLOAT64_DESC',
         'c32': 'SDL_COMPLEX32_DESC', 'c64': 'SDL_COMPLEX64_DESC',
         'string': 'SDL_STRING_DESC'}
      if name in descriptors:
         return '&' + descriptors[name]
      if name in self.enums:
         return '&SDL_ENUM_' + name.upper() + '_DESC'
      return '&' + name.upper() + '_DESC'

   def generate_c_files(self, base_name='schema'):
      identifier = c_identifier(base_name)
      guard = identifier.upper() + '_H'
      header = [
         '/* Generated by the SDL C backend. */\n',
         '#ifndef ' + guard + '\n#define ' + guard + '\n\n',
         '#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n',
         '#include <complex.h>\n#include "type_descriptors.h"\n\n']
      source = ['/* Generated by the SDL C backend. */\n',
         '#include "' + base_name + '.h"\n#include "type_registry.h"\n#include <stddef.h>\n\n']

      for enum in self.enums.values():
         header.append('typedef enum {\n')
         for name, value in enum.pairs:
            header.append('   ' + enum.name.upper() + '_' + name + ' = ' + value + ',\n')
         header.append('} ' + enum.name + ';\n')
         header.append('extern const SdlTypeDesc SDL_ENUM_' + enum.name.upper() + '_DESC;\n\n')
         source.append('typedef struct { char prefix; ' + enum.name +
            ' value; } SDL_ALIGN_' + enum.name.upper() + ';\n')
         source.append('const SdlTypeDesc SDL_ENUM_' + enum.name.upper() + '_DESC = {\n')
         source.append('   SDL_TYPE_ENUM, sizeof(' + enum.name + '), offsetof(SDL_ALIGN_' +
            enum.name.upper() + ', value),\n')
         source.append('   "' + enum.name + '", 0, { { 0, NULL } }\n};\n\n')

      for name in self.message_order:
         message = self.messages[name]
         header.append('typedef struct {\n')
         for field in sorted(message.fields, key=lambda item: item.index):
            c_type = self._c_type(field.type_name)
            if field.modifier == 'optional':
               header.append('   bool has_' + field.name + ';\n')
            if field.modifier == 'repeated':
               header.append('   uint32_t ' + field.name + '_count;\n')
               header.append('   ' + c_type + ' *' + field.name + ';\n')
            else:
               header.append('   ' + c_type + ' ' + field.name + ';\n')
         header.append('} ' + name + ';\n')
         header.append('extern const SdlTypeDesc ' + name.upper() + '_DESC;\n\n')
         header.append('#define ' + name.upper() + '_HASH 0x' +
            format(fnv1a_32(name), '08X') + 'U\n')

      header.append('\nvoid register_' + identifier + '_types(void);\n\n#endif\n')
      for name in self.message_order:
         fields = sorted(self.messages[name].fields, key=lambda item: item.index)
         source.append('static const SdlFieldDesc ' + name.lower() + '_fields[] = {\n')
         if not fields:
            source.append('   { 0, NULL, NULL, 0, SDL_NO_OFFSET, SDL_NO_OFFSET, 0 }\n')
         for field in fields:
            presence = 'offsetof(' + name + ', has_' + field.name + ')' if field.modifier == 'optional' else 'SDL_NO_OFFSET'
            count = 'offsetof(' + name + ', ' + field.name + '_count)' if field.modifier == 'repeated' else 'SDL_NO_OFFSET'
            flags = 'SDL_FIELD_OPTIONAL' if field.modifier == 'optional' else '0'
            if field.modifier == 'repeated':
               flags += ' | SDL_FIELD_REPEATED'
            source.append('   { ' + str(field.index) + 'U, "' + field.name + '", ' +
               self._type_desc(field.type_name) + ', offsetof(' + name + ', ' + field.name +
               '), ' + presence + ', ' + count + ', ' + flags + ' },\n')
         source.append('};\n')
         source.append('typedef struct { char prefix; ' + name +
            ' value; } SDL_ALIGN_' + name.upper() + ';\n')
         source.append('const SdlTypeDesc ' + name.upper() + '_DESC = {\n')
         source.append('   SDL_TYPE_STRUCT, sizeof(' + name + '), offsetof(SDL_ALIGN_' +
            name.upper() + ', value),\n')
         source.append('   "' + name + '", ' + name.upper() + '_HASH,\n')
         source.append('   { { ' + str(len(fields)) + ', ' + name.lower() + '_fields } }\n};\n\n')
      source.append('void register_' + identifier + '_types(void) {\n')
      for name in self.message_order:
         source.append('   (void)sdl_register_type(&' + name.upper() + '_DESC);\n')
      source.append('}\n')
      return ''.join(header), ''.join(source)


if __name__ == '__main__':
   input_path = sys.argv[1] if len(sys.argv) > 1 else 'sdl'
   output_dir = sys.argv[2] if len(sys.argv) > 2 else 'build/generated'
   if os.path.isdir(input_path):
      schema_paths = [os.path.join(input_path, item) for item in sorted(os.listdir(input_path))
         if item.endswith('.sdl') and os.path.isfile(os.path.join(input_path, item))]
   else:
      schema_paths = [input_path]
   if not schema_paths:
      raise ValueError('no .sdl files found in ' + input_path)

   os.makedirs(output_dir, exist_ok=True)
   generated = []
   seen_bases = set()
   seen_type_names = set()
   seen_symbols = set()
   for schema_path in schema_paths:
      base_name = os.path.splitext(os.path.basename(schema_path))[0]
      identifier = c_identifier(base_name)
      if identifier in seen_bases:
         raise ValueError('SDL filenames map to the same C identifier: ' + identifier)
      seen_bases.add(identifier)
      parser = MsgParser()
      with open(schema_path, 'r', encoding='utf-8') as input_file:
         parser.parse_text(input_file.read())
      for name in list(parser.enums) + list(parser.messages):
         symbol = name.upper()
         if name in seen_type_names or symbol in seen_symbols:
            raise ValueError('duplicate type name across SDL files: ' + name)
         seen_type_names.add(name)
         seen_symbols.add(symbol)
      header, source = parser.generate_c_files(base_name)
      with open(os.path.join(output_dir, base_name + '.h'), 'w', encoding='utf-8') as output_file:
         output_file.write(header)
      with open(os.path.join(output_dir, base_name + '.c'), 'w', encoding='utf-8') as output_file:
         output_file.write(source)
      generated.append((base_name, identifier))

   registry_header = [
      '/* Generated registry for SDL files in the input directory. */\n',
      '#ifndef SDL_REGISTRY_H\n#define SDL_REGISTRY_H\n\n',
      'void register_all_types(void);\n\n#endif\n']
   registry_source = ['/* Generated registry for SDL files in the input directory. */\n',
      '#include "sdl_registry.h"\n']
   for base_name, unused_identifier in generated:
      registry_source.append('#include "' + base_name + '.h"\n')
   registry_source.append('\nvoid register_all_types(void) {\n')
   for unused_base_name, identifier in generated:
      registry_source.append('   register_' + identifier + '_types();\n')
   registry_source.append('}\n')
   with open(os.path.join(output_dir, 'sdl_registry.h'), 'w', encoding='utf-8') as output_file:
      output_file.write(''.join(registry_header))
   with open(os.path.join(output_dir, 'sdl_registry.c'), 'w', encoding='utf-8') as output_file:
      output_file.write(''.join(registry_source))
