#!/usr/bin/env python3
"""Python 3 code generation for SDL schemas."""

import keyword
import os
import unicodedata

from generator import c_identifier, canonical_type_descriptor, clear_generated_outputs, parse_schemas


_PYTHON_IMPORTED_TYPES = set(('IntEnum Complex32 Complex64 SdlMessage').split())
_PYTHON_MESSAGE_RESERVED_FIELDS = set((
   '_SDL_DESCRIPTOR _SDL_NAME _SDL_FIXED_SIZE _SDL_FIELDS display __init__ __eq__ __repr__ __class__ __dict__ '
   '__weakref__').split())


def _is_python_identifier(value):
   return (value.isidentifier() and not keyword.iskeyword(value) and
      unicodedata.normalize('NFKC', value) == value)


class PythonBackend:
   def __init__(self, schema):
      self.schema = schema

   def _validate_python_identifiers(self):
      generated_types = {}
      for name in list(self.schema.enums) + list(self.schema.message_order):
         generated = c_identifier(name)
         if not _is_python_identifier(generated):
            raise ValueError('Python backend cannot emit invalid type identifier: ' +
               name)
         if generated in _PYTHON_IMPORTED_TYPES:
            raise ValueError('Python type name conflicts with an imported runtime type: ' +
               name)
         if generated in generated_types:
            raise ValueError('Python type name collision after conversion: ' + name +
               ' and ' + generated_types[generated])
         generated_types[generated] = name

      for enumeration in self.schema.enums.values():
         generated_values = {}
         for name, unused_value in enumeration.pairs:
            generated = c_identifier(name)
            if (not _is_python_identifier(generated) or generated == 'mro' or
                (name.startswith('_') and name.endswith('_'))):
               raise ValueError('Python backend cannot emit invalid or reserved enum item: ' +
                  enumeration.name + '.' + name)
            if generated in generated_values:
               raise ValueError('Python enum item collision after conversion in ' +
                  enumeration.name + ': ' + name + ' and ' + generated_values[generated])
            generated_values[generated] = name

      for message_name in self.schema.message_order:
         generated_fields = {}
         for field in self.schema.messages[message_name].fields:
            generated = c_identifier(field.name)
            if not _is_python_identifier(generated):
               raise ValueError('Python backend cannot emit invalid field identifier: ' +
                  message_name + '.' + field.name)
            if generated in _PYTHON_MESSAGE_RESERVED_FIELDS:
               raise ValueError('Python field name conflicts with runtime metadata or methods: ' +
                  message_name + '.' + field.name)
            if generated in generated_fields:
               raise ValueError('Python field name collision after conversion in ' +
                  message_name + ': ' + field.name + ' and ' + generated_fields[generated])
            generated_fields[generated] = field.name

   def _python_type(self, type_name):
      types = {
         'bool': 'bool', 'int8': 'int', 'int16': 'int', 'int32': 'int',
         'int64': 'int', 'fl32': 'float', 'fl64': 'float',
         'c32': 'Complex32', 'c64': 'Complex64', 'string': 'str',
      }
      return types.get(type_name, c_identifier(type_name))

   def generate(self):
      self._validate_python_identifiers()
      output = [
         '# Generated by the SDL Python backend.\n',
         'from enum import IntEnum\n',
         'from sdl_runtime import Complex32, Complex64, SdlMessage\n\n',
      ]
      for enum in self.schema.enums.values():
         output.append('class ' + c_identifier(enum.name) + '(IntEnum):\n')
         if enum.pairs:
            for name, value in enum.pairs:
               output.append('   ' + c_identifier(name) + ' = ' + value + '\n')
         else:
            output.append('   pass\n')
         output.append('\n')

      for message_name in self.schema.message_order:
         fields = sorted(self.schema.messages[message_name].fields,
            key=lambda field: field.index)
         output.append('class ' + c_identifier(message_name) + '(SdlMessage):\n')
         descriptor = canonical_type_descriptor(self.schema, message_name)
         output.append('   _SDL_NAME = ' + repr(message_name) + '\n')
         output.append('   _SDL_DESCRIPTOR = ' + repr(descriptor.decode('utf-8')) + '\n')
         fixed_size = self.schema.fixed_wire_size(message_name)
         if fixed_size is not None:
            output.append('   _SDL_FIXED_SIZE = ' + str(fixed_size) + '\n')
         output.append('   _SDL_FIELDS = (\n')
         for field in fields:
            output.append('      (' + str(field.index) + ', ' + repr(c_identifier(field.name)) +
               ', ' + repr(field.modifier) + ', ' + repr(field.type_name) + ', ' +
               repr(tuple(field.array_dimensions)) + '),\n')
         output.append('   )\n\n')
      return ''.join(output)


def generate_python(input_path, output_dir):
   schemas = parse_schemas(input_path)
   modules = []
   seen_modules = set()
   for base_name, unused_identifier, schema in schemas:
      module_name = c_identifier(base_name).lower()
      if not _is_python_identifier(module_name):
         raise ValueError('invalid Python module name from SDL filename: ' + base_name)
      if module_name == '__init__':
         raise ValueError('Python schema filename __init__ collides with generated package initializer')
      if module_name in seen_modules:
         raise ValueError('SDL filenames map to the same Python module: ' + module_name)
      seen_modules.add(module_name)
      PythonBackend(schema)._validate_python_identifiers()
      modules.append((module_name, schema))

   clear_generated_outputs(output_dir, ('.py',), (
      '# Generated by the SDL Python backend.',))
   for module_name, schema in modules:
      output_path = os.path.join(output_dir, module_name + '.py')
      with open(output_path, 'w', encoding='utf-8') as output_file:
         output_file.write(PythonBackend(schema).generate())

   with open(os.path.join(output_dir, '__init__.py'), 'w', encoding='utf-8') as output_file:
      output_file.write('# Generated by the SDL Python backend.\n')
      for module, unused_schema in modules:
         output_file.write('from .' + module + ' import *\n')
